package io.github.krosstack.kscope.engine.discovery

import io.github.krosstack.kscope.model.Artifact
import io.github.krosstack.kscope.model.ArtifactCategory
import io.github.krosstack.kscope.model.ArtifactRef
import io.github.krosstack.kscope.model.ArtifactType
import io.github.krosstack.kscope.model.ContentHash
import io.github.krosstack.kscope.model.GeneratedInfo
import io.github.krosstack.kscope.model.RepoPath
import io.github.krosstack.kscope.model.RepositoryId
import io.github.krosstack.kscope.spi.OutputRoot
import kotlin.test.Test
import kotlin.test.assertFalse
import kotlin.test.assertTrue

class GeneratedRootPolicyTest {
    private fun artifact(generated: GeneratedInfo?) = Artifact(
        ref = ArtifactRef(RepositoryId("repository"), RepoPath("dist/index.js")),
        type = ArtifactType("javascript.source", ArtifactCategory.SOURCE),
        contentHash = ContentHash("hash"),
        sizeBytes = 1,
        lineCount = 1,
        sourceSet = null,
        generated = generated,
    )

    @Test
    fun `hand-written files are handed to producers`() {
        assertTrue(GeneratedRootPolicy.isHandedToProducers(artifact(generated = null)))
    }

    @Test
    fun `files marked generated by a build model or by the scope are withheld`() {
        assertFalse(GeneratedRootPolicy.isHandedToProducers(artifact(GeneratedInfo("ksp", null))))
        assertFalse(GeneratedRootPolicy.isHandedToProducers(artifact(GeneratedInfo("settings", null))))
    }

    @Test
    fun `files labelled as outputs are handed to producers`() {
        val label = OutputRoot(RepoPath("dist"), "vite").label

        assertTrue(GeneratedRootPolicy.isHandedToProducers(artifact(GeneratedInfo(label, null))))
    }
}
