package io.github.krosstack.kscope.analyzer.jni

import io.github.krosstack.kscope.analyzer.jni.natives.NativeFunction
import io.github.krosstack.kscope.analyzer.jni.natives.NativeFunctionScanner
import io.github.krosstack.kscope.analyzer.jni.natives.NativeRole
import io.github.krosstack.kscope.model.TextRange
import kotlin.test.Test
import kotlin.test.assertEquals

class NativeFunctionScannerTest {
    private fun scan(text: String): List<NativeFunction> = NativeFunctionScanner(text).scan()

    private fun roles(text: String): List<Pair<String, NativeRole>> = scan(text).map { it.name to it.role }

    @Test
    fun `definitions of the reference workspace are found with the positions of the name and of the whole function`() {
        val (crc32, version) = scan(CHECKSUM_C)
        assertEquals("Java_sample_tasktide_nativebridge_Checksum_crc32", crc32.name)
        assertEquals(NativeRole.DEFINITION, crc32.role)
        assertEquals(TextRange(10, 1, 10, 49), crc32.nameRange)
        assertEquals(TextRange(9, 1, 13, 2), crc32.declaration)
        assertEquals(
            "JNIEXPORT jint JNICALL Java_sample_tasktide_nativebridge_Checksum_crc32" +
                "(JNIEnv *env, jobject thiz, jbyteArray data)",
            crc32.signature,
        )
        assertEquals("Java_sample_tasktide_nativebridge_Checksum_nativeVersion", version.name)
        assertEquals(TextRange(15, 1, 18, 2), version.declaration)
    }

    @Test
    fun `a generated header gives declarations inside the extern block`() {
        val header = """
            /* DO NOT EDIT THIS FILE - it is machine generated */
            #include <jni.h>
            #ifndef _Included_p_C
            #define _Included_p_C
            #ifdef __cplusplus
            extern "C" {
            #endif
            /*
             * Class:     p_C
             * Signature: ([B)I
             */
            JNIEXPORT jint JNICALL Java_p_C_crc32
              (JNIEnv *, jobject, jbyteArray);

            JNIEXPORT void JNICALL Java_p_C_reset__I
              (JNIEnv *, jobject, jint);
            #ifdef __cplusplus
            }
            #endif
            #endif
        """.trimIndent()
        val (crc32, reset) = scan(header)
        assertEquals(NativeRole.DECLARATION, crc32.role)
        assertEquals("JNIEXPORT jint JNICALL Java_p_C_crc32 (JNIEnv *, jobject, jbyteArray)", crc32.signature)
        assertEquals(TextRange(12, 1, 13, 35), crc32.declaration)
        assertEquals(listOf("Java_p_C_crc32", "Java_p_C_reset__I"), listOf(crc32.name, reset.name))
    }

    @Test
    fun `c plus plus linkage, namespaces, attributes and pointer results are accepted`() {
        val source = """
            namespace bridge {
            extern "C" JNIEXPORT jstring JNICALL Java_p_Cls_hello(JNIEnv* env, jobject) noexcept {
                return env->NewStringUTF("hi");
            }
            }
            jobject *Java_p_Cls_pointer(JNIEnv *env);
        """.trimIndent()
        val functions = scan(source)
        assertEquals(listOf("Java_p_Cls_hello", "Java_p_Cls_pointer"), functions.map { it.name })
        assertEquals("JNIEXPORT jstring JNICALL Java_p_Cls_hello(JNIEnv* env, jobject)", functions[0].signature)
        assertEquals(listOf(NativeRole.DEFINITION, NativeRole.DECLARATION), functions.map { it.role })
    }

    @Test
    fun `comments, strings, raw strings and macros are not code`() {
        val source = """
            // Java_p_C_lineComment(JNIEnv *env);
            /* JNIEXPORT void JNICALL Java_p_C_blockComment(JNIEnv *env); */
            static const char *text = "JNIEXPORT void JNICALL Java_p_C_string(JNIEnv *env);";
            static const char *raw = R"x(JNIEXPORT void JNICALL Java_p_C_raw(JNIEnv *env);)x";
            #define CALL Java_p_C_macro(1)
            #define LONG_MACRO(a) \
                Java_p_C_continued(a)
            JNIEXPORT void JNICALL Java_p_C_real(JNIEnv *env);
        """.trimIndent()
        assertEquals(listOf("Java_p_C_real"), scan(source).map { it.name })
    }

    @Test
    fun `a call inside a function body or an initializer is no function`() {
        val source = """
            JNIEXPORT void JNICALL Java_p_C_outer(JNIEnv *env, jobject self) {
                Java_p_C_inner(env, self);
                if (self) { Java_p_C_nested(env, self); }
            }
            static int value = Java_p_C_initializer(1);
            void helper(void) { return Java_p_C_helperCall(); }
        """.trimIndent()
        assertEquals(listOf("Java_p_C_outer"), scan(source).map { it.name })
    }

    @Test
    fun `a prototype and the definition of one function are both reported`() {
        val source = """
            JNIEXPORT void JNICALL Java_p_C_f(JNIEnv *env, jobject self);
            JNIEXPORT void JNICALL Java_p_C_f(JNIEnv *env, jobject self) {
            }
        """.trimIndent()
        assertEquals(
            listOf("Java_p_C_f" to NativeRole.DECLARATION, "Java_p_C_f" to NativeRole.DEFINITION),
            roles(source),
        )
    }

    @Test
    fun `windows line ends give the lines an editor shows`() {
        val function = scan("#include <jni.h>\r\n\r\nvoid\r\nJava_p_C_f(void) {\r\n}\r\n").single()
        assertEquals(TextRange(4, 1, 4, 11), function.nameRange)
        assertEquals(TextRange(3, 1, 5, 2), function.declaration)
    }

    @Test
    fun `text that is not c never fails`() {
        listOf("", "/* never closed", "\"never closed", "Java_p_C_f(", "Java_p_C_f(int", "{ { {", "}}} Java_x", "R\"(")
            .forEach { assertEquals(emptyList(), scan(it), it) }
    }

    @Test
    fun `a name without a type before it and a name that is only used are not functions`() {
        assertEquals(emptyList(), roles("Java_p_C_f(1);\nint (*p)(void) = Java_p_C_g;\n"))
    }
}
