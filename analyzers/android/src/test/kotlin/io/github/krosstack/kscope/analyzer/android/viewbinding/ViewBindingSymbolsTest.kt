package io.github.krosstack.kscope.analyzer.android.viewbinding

import io.github.krosstack.kscope.analyzer.android.Render
import io.github.krosstack.kscope.model.Certainty
import io.github.krosstack.kscope.model.EvidenceClass
import io.github.krosstack.kscope.model.NodeRef
import io.github.krosstack.kscope.model.Relationship
import io.github.krosstack.kscope.model.Resolution
import io.github.krosstack.kscope.model.Symbol
import io.github.krosstack.kscope.model.SymbolCategory
import io.github.krosstack.kscope.model.SymbolFlag
import io.github.krosstack.kscope.model.SymbolOrigin
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNull
import kotlin.test.assertTrue

internal class ViewBindingSymbolsTest : ViewBindingTestBase() {
    private val result = run()
    private val databinding = "sample.droid.app.databinding"

    private fun symbolNamed(qualifiedName: String, from: BindingResult = result): Symbol =
        from.symbols().single { it.qualifiedName == qualifiedName }

    private fun BindingResult.generatorsOf(symbol: Symbol): List<Relationship> =
        generates().filter { (it.resolution as Resolution.Resolved).target == NodeRef.OfSymbol(symbol.id) }

    private fun Symbol.sourceOfTruth(): String =
        Render.node(checkNotNull((origin as SymbolOrigin.Generated).sourceOfTruth))

    @Test
    fun `layout names become pascal case class names and ids camel case field names`() {
        assertEquals("FragmentTaskListBinding", BindingNames.classNameOf("fragment_task_list"))
        assertEquals("Item2RowBinding", BindingNames.classNameOf("item_2_row"))
        assertEquals("ActivityMainBinding", BindingNames.classNameOf("activity__main_"))
        assertEquals("priorityDot", BindingNames.fieldNameOf("priority_dot"))
        assertEquals("taskListFragment", BindingNames.fieldNameOf("taskListFragment"))
        assertEquals("itemCount2", BindingNames.fieldNameOf("item_count_2"))
        assertEquals("view2d", BindingNames.fieldNameOf("view_2d"))
        assertEquals("title", BindingNames.fieldNameOf("Title"))
        assertEquals("aBC", BindingNames.fieldNameOf("a_b_c"))
    }

    @Test
    fun `the class, its fields and its methods are symbols whose ids follow the descriptor of the stub`() {
        val badge = result.symbols().filter { it.qualifiedName?.contains("ViewBadgeBinding") == true }
        val prefix = ":app@main:sample/droid/app/databinding/ViewBadgeBinding#"
        assertEquals(
            listOf(
                prefix,
                "${prefix}badgeText.",
                "${prefix}getRoot().",
                "${prefix}inflate(LayoutInflater).",
                "${prefix}inflate(LayoutInflater,ViewGroup,boolean).",
                "${prefix}bind(View).",
            ),
            badge.map { Render.id(it.id) },
        )
    }

    @Test
    fun `a merge layout inflates into a parent and has a root of type view`() {
        val members = result.symbols().filter { it.qualifiedName?.contains("ViewRowsBinding.") == true }
        assertEquals(listOf("firstRow", "getRoot", "inflate", "bind"), members.map { it.name })
        val inflate = members.single { it.name == "inflate" }
        assertTrue("android.view.ViewGroup parent" in inflate.signature.orEmpty())
    }

    @Test
    fun `symbols are generated java symbols with signatures as the stub writes them`() {
        val field = symbolNamed("$databinding.ActivityMainBinding.priority")
        assertEquals("java.field", field.kind.id)
        assertEquals(SymbolCategory.VARIABLE, field.kind.category)
        assertEquals("public final com.example.ui.widget.PriorityView priority", field.signature)
        val inflate = result.symbols().filter { it.name == "inflate" && it.container == field.container }
        assertEquals(2, inflate.size)
        assertTrue(inflate.all { SymbolFlag.STATIC in it.flags && it.kind.id == "java.method" })
        assertNull(field.declaration)
        assertEquals(EvidenceClass.CONVENTION, field.evidenceClass)
        assertEquals(Certainty.EXACT, field.certainty)
    }

    @Test
    fun `a class is generated by its layout and a field by the id resource that declares it`() {
        val binding = symbolNamed("$databinding.ActivityMainBinding")
        val title = symbolNamed("$databinding.ActivityMainBinding.title")
        assertEquals("android.viewbinding", (binding.origin as SymbolOrigin.Generated).generator)
        assertEquals(":app@main:android/res/layout/activity_main.", binding.sourceOfTruth())
        assertEquals(":app@main:android/res/id/title.", title.sourceOfTruth())
        val edge = result.generatorsOf(title).single()
        assertEquals(":app@main:android/res/id/title.", Render.node(edge.from))
        assertEquals(EvidenceClass.CONVENTION, edge.evidenceClass)
        assertEquals(Certainty.EXACT, (edge.resolution as Resolution.Resolved).certainty)
    }

    @Test
    fun `a layout of a variant source set generates the class from the resource of that source set`() {
        val banner = symbolNamed("$databinding.DebugBannerBinding")
        val edge = result.generatorsOf(banner).single()
        assertEquals(":app@debug:android/res/layout/debug_banner.", Render.node(edge.from))
    }

    @Test
    fun `a layout that several source sets define generates the class from each definition`() {
        val debugBadge = "<TextView xmlns:android=\"http://schemas.android.com/apk/res/android\"" +
            " android:id=\"@+id/badge_text\"/>"
        val merged = run(treeWithBinding(mapOf("app/src/debug/res/layout/view_badge.xml" to debugBadge)))
        val badge = symbolNamed("$databinding.ViewBadgeBinding", merged)
        assertEquals(
            listOf(":app@debug:android/res/layout/view_badge.", ":app@main:android/res/layout/view_badge."),
            merged.generatorsOf(badge).map { Render.node(it.from) }.sorted(),
        )
    }

    @Test
    fun `an id that is only used and not declared has a field and no generating resource`() {
        val used = "<TextView xmlns:android=\"http://schemas.android.com/apk/res/android\"" +
            " android:id=\"@id/shared_id\"/>"
        val bound = run(treeWithBinding(mapOf("app/src/main/res/layout/view_badge.xml" to used)))
        val field = symbolNamed("$databinding.ViewBadgeBinding.sharedId", bound)
        assertEquals(emptyList(), bound.generatorsOf(field))
        assertEquals(":app@main:android/res/layout/view_badge.", field.sourceOfTruth())
    }
}
