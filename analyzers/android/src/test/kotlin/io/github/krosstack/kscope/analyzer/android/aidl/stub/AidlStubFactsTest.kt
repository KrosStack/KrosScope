import io.github.krosstack.kscope.model.SymbolOrigin
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

private const val GENERATED_ID = ":svc@main:sample/tasktide/sync/service/ISyncService#"
private const val AIDL_ID = ":svc@main:aidl/sample/tasktide/sync/service/ISyncService#"

class AidlStubFactsTest {
    private val synthesis = AidlWorkspace(syncSample()).synthesize()

    private val symbols = AidlWorkspace(syncSample()).synthesize { it.ref.path.value == AidlPaths.SERVICE }
        .facts.filterIsInstance<Fact.OfSymbol>().map { it.value }

    @Test
    fun `the facts of the surfaces match the golden file`() {
        Golden.assertMatches("aidl-surface.jsonl", Golden.facts(synthesis.batches))
    }

    @Test
    fun `the generated symbols have the ids that the analyzer derives from the stub`() {
        assertEquals(
            listOf(
                GENERATED_ID,
                "${GENERATED_ID}DESCRIPTOR.",
                "${GENERATED_ID}startSync().",
                "${GENERATED_ID}getStatus().",
                "${GENERATED_ID}registerCallback(ISyncCallback).",
                "${GENERATED_ID}unregisterCallback(ISyncCallback).",
                "${GENERATED_ID}Default#",
                "${GENERATED_ID}Stub#",
                "${GENERATED_ID}Stub#asInterface(IBinder).",
                "${GENERATED_ID}Stub#asBinder().",
            ),
            symbols.map { Render.id(it.id) },
        )
    }

    @Test
    fun `generated symbols are marked generated, nested members static and interface methods abstract`() {
        val byName = symbols.associateBy { it.qualifiedName }
        val stub = byName.getValue("sample.tasktide.sync.service.ISyncService.Stub")
        val origin = stub.origin as SymbolOrigin.Generated
        assertEquals("android.aidl", origin.generator)
        assertEquals(AIDL_ID, Render.node(checkNotNull(origin.sourceOfTruth)))
        assertEquals(setOf(SymbolFlag.STATIC, SymbolFlag.ABSTRACT), stub.flags)
        assertEquals(
            "public static abstract class Stub extends android.os.Binder implements " +
                "sample.tasktide.sync.service.ISyncService",
            stub.signature,
        )
        val method = byName.getValue("sample.tasktide.sync.service.ISyncService.startSync")
        assertEquals(setOf(SymbolFlag.ABSTRACT), method.flags)
        assertEquals(EvidenceClass.CONVENTION, stub.evidenceClass)
        assertEquals(Certainty.EXACT, stub.certainty)
        assertEquals("stub", stub.attributes["aidl.role"])
    }

    @Test
    fun `the interface and its stub are generated by the contract and each method by its aidl method`() {
        val edges = synthesis.facts.filterIsInstance<Fact.OfRelationship>().map { it.value }
        assertTrue(edges.all { it.kind == RelationKind.GENERATES && it.evidenceClass == EvidenceClass.CONVENTION })
        assertTrue(edges.all { (it.resolution as Resolution.Resolved).certainty == Certainty.EXACT })
        val lines = edges.map { Render.node(it.from) to Render.node((it.resolution as Resolution.Resolved).target) }
        assertTrue(AIDL_ID to GENERATED_ID in lines)
        assertTrue(AIDL_ID to "${GENERATED_ID}Stub#" in lines)
        assertTrue("${AIDL_ID}startSync()." to "${GENERATED_ID}startSync()." in lines)
        val registered = "registerCallback(ISyncCallback)."
        assertTrue("$AIDL_ID$registered" to "$GENERATED_ID$registered" in lines)
    }
}
