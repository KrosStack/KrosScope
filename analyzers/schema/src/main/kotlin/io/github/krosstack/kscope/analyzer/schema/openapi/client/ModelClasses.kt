package io.github.krosstack.kscope.analyzer.schema.openapi.client

import io.github.krosstack.kscope.analyzer.schema.openapi.OpenApiIdentities
import io.github.krosstack.kscope.analyzer.schema.openapi.OpenApiProperty
import io.github.krosstack.kscope.analyzer.schema.openapi.OpenApiSchema
import io.github.krosstack.kscope.analyzer.schema.stub.StubClass
import io.github.krosstack.kscope.analyzer.schema.stub.StubForm
import io.github.krosstack.kscope.analyzer.schema.stub.StubParameter
import io.github.krosstack.kscope.analyzer.schema.stub.StubTruth

/**
 * The data classes of the models of a client: one for each schema in [schemas], with a property for each property of
 * the schema, the required ones first. The class is generated from its schema; its properties name the schema as their
 * source without being generated by it.
 */
internal class ModelClasses(
    private val schemas: List<OpenApiSchema>,
    private val ids: OpenApiIdentities,
    private val types: ClientTypes,
) {
    fun classes(): List<StubClass> = schemas.map(::classOf)

    private fun classOf(schema: OpenApiSchema) = StubClass(
        name = ClientNames.upperCamel(schema.name),
        form = StubForm.DATA_CLASS,
        constructor = schema.properties.map(::parameterOf).distinctBy { it.name }.sortedBy { it.default != null },
        truth = StubTruth(ids.schemaId(schema), direct = true),
    )

    private fun parameterOf(property: OpenApiProperty): StubParameter =
        types.parameter(ClientNames.lowerCamel(property.name), property.type, property.required, isProperty = true)
}
