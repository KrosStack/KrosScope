package io.github.krosstack.kscope.analyzer.schema

import io.github.krosstack.kscope.analyzer.schema.proto.WireKotlinSynthesizer
import io.github.krosstack.kscope.model.EvidenceClass
import io.github.krosstack.kscope.model.Fact
import io.github.krosstack.kscope.model.NodeRef
import io.github.krosstack.kscope.model.RelationKind
import io.github.krosstack.kscope.model.Resolution
import io.github.krosstack.kscope.model.Symbol
import io.github.krosstack.kscope.model.SymbolOrigin
import io.github.krosstack.kscope.spi.SyntheticSource
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

class WireKotlinSynthesizerTest {
    private val path = "lib/src/main/proto/library.proto"
    private val files = mapOf(path to Resources.text("wire/library.proto"))
    private val wire = mapOf("wire.kotlin" to "true")
    private val synthesizer = WireKotlinSynthesizer()

    private fun run(attributes: Map<String, String> = wire) =
        TestWorkspace(files, listOf(ModuleSpec(":lib", attributes = attributes))).synthesize(synthesizer)

    private fun symbols(): List<Symbol> = run().first.facts().symbols()

    @Test
    fun `a module that has Wire generate Kotlin gets a stub in the source set of the proto file`() {
        val (_, sources) = run()
        val stub = sources.single()
        assertEquals("kotlin", stub.language)
        assertEquals("wire", stub.generator)
        assertEquals(TestRepository.sourceSetId(":lib", "main"), stub.sourceSet)
    }

    @Test
    fun `a module without the Wire Kotlin attribute gets nothing`() {
        val (batches, sources) = run(emptyMap())
        assertEquals(emptyList<SyntheticSource>(), sources)
        assertEquals(emptyList(), batches.facts())
    }

    @Test
    fun `the stub follows the naming rules of the Wire generator`() {
        Golden.assertMatches("wire-library.kt.txt", run().second.single().text)
    }

    @Test
    fun `message classes get a constructor, field properties, copy and a companion with the adapter`() {
        val prefix = "sample.library.wire.Book."
        val described = symbols().mapNotNull { symbol ->
            symbol.qualifiedName?.removePrefix(
                prefix,
            )?.takeIf { it != symbol.qualifiedName }?.let { symbol to it }
        }
            .filter { (_, rest) -> "." !in rest }
            .map { (symbol, _) -> "${symbol.kind.id} ${symbol.name}" }
        assertEquals(
            listOf(
                "kotlin.constructor <init>", "kotlin.property title", "kotlin.property pages", "kotlin.property genre",
                "kotlin.property authors", "kotlin.property stock", "kotlin.property subtitle",
                "kotlin.property publisher", "kotlin.property cover", "kotlin.property borrower", "kotlin.property due",
                "kotlin.property added", "kotlin.function copy", "kotlin.class Publisher", "kotlin.object Companion",
            ),
            described,
        )
    }

    @Test
    fun `the ids are the ones the analyzer derives from the stub syntax`() {
        val ids = symbols().map { Render.id(it.id) }
        val constructor = "String,Int,Genre,List,Map,String,Publisher,ByteString,String,Long,Timestamp,ByteString"
        listOf(
            "sample/library/wire/Book#",
            "sample/library/wire/Book#title.",
            "sample/library/wire/Book#`<init>`($constructor).",
            "sample/library/wire/Book#copy($constructor).",
            "sample/library/wire/Book#Companion#ADAPTER.",
            "sample/library/wire/Book#Publisher#name.",
            "sample/library/wire/Genre#FICTION.",
            "sample/library/wire/Genre#`<init>`(Int).",
            "sample/library/wire/Genre#value.",
            "sample/library/wire/Genre#Companion#fromValue(Int).",
        ).forEach { expected -> assertTrue(":lib@main:$expected" in ids, "$expected in $ids") }
    }

    @Test
    fun `generated symbols name their proto source of truth and are generated by Wire`() {
        val title = symbols().single { it.qualifiedName == "sample.library.wire.Book.title" }
        val origin = title.origin as SymbolOrigin.Generated
        assertEquals("wire", origin.generator)
        val source = (origin.sourceOfTruth as NodeRef.OfSymbol).id
        assertEquals(":lib@main:proto/sample/library/Book#title.", Render.id(source))
        assertEquals(EvidenceClass.CONVENTION, title.evidenceClass)
    }

    @Test
    fun `GENERATES relationships join messages, fields, enums and constants to their classes`() {
        val facts = run().first.facts()
        val symbols = facts.symbols().associateBy { it.id }
        val generated = facts.relationships().filter { it.kind == RelationKind.GENERATES }
        val described = generated.map { Render.relationship(it).replace(":lib@main:", "") }
        listOf(
            "proto/sample/library/Book# -> sample/library/wire/Book#",
            "proto/sample/library/Book#due. -> sample/library/wire/Book#due.",
            "proto/sample/library/Genre# -> sample/library/wire/Genre#",
            "proto/sample/library/Genre#FICTION. -> sample/library/wire/Genre#FICTION.",
        ).forEach { edge -> assertTrue("GENERATES/ $edge CONVENTION" in described, "$edge in $described") }
        generated.forEach { edge ->
            val resolution = edge.resolution as Resolution.Resolved
            val symbol = symbols.getValue((resolution.target as NodeRef.OfSymbol).id)
            assertEquals(symbol.certainty, resolution.certainty, symbol.qualifiedName)
        }
        assertEquals(
            1 + 11 + 1 + 1 + 1 + 2,
            generated.size,
            "Book, 11 fields, Publisher, its field, Genre, 2 constants",
        )
    }

    @Test
    fun `a proto file outside every source set is noted and gets no stub`() {
        val workspace = TestWorkspace(
            mapOf("lib/proto/x.proto" to "syntax = \"proto3\"; message A {}"),
            listOf(ModuleSpec(":lib", attributes = wire)),
        )
        val (batches, sources) = workspace.synthesize(synthesizer)
        assertEquals(emptyList<SyntheticSource>(), sources)
        assertEquals(
            "wire.no-source-set",
            batches.facts().filterIsInstance<Fact.OfDiagnostic>().single().value.code.value,
        )
    }
}
