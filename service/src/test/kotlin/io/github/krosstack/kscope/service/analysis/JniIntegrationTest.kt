/**
 * Scans a library with Kotlin `external` functions, a Java `native` method and C and C++ files, with the real analyzer
 * worker, and follows each native method to its function through the contract that the JNI linker makes for it.
 */
class JniIntegrationTest {
    private val sample = SampleWorkspace("jni")
    private val nativeFiles = listOf("checksum.c", "javanative.cpp", "mix.h").map { "bridge/src/main/cpp/$it" }

    @AfterTest
    fun cleanUp() {
        sample.close()
    }

    private fun GraphReader.symbolOf(node: NodeRef?): Symbol? = (node as? NodeRef.OfSymbol)?.let { symbol(it.id) }

    private fun GraphReader.bindings(): List<Relationship> =
        relationships(RelationshipQuery(kinds = setOf(RelationKind.BINDS), limit = Int.MAX_VALUE))
            .filter { symbolOf(it.from)?.kind?.id == "jni.function" }

    private fun GraphReader.outcomes(): Map<String, String> = bindings().associate { binding ->
        val outcome = when (val resolution = binding.resolution) {
            is Resolution.Resolved -> {
                val role = symbolOf(resolution.target)?.attributes?.get("jni.role")
                "$role ${resolution.certainty}"
            }

            is Resolution.Unresolved -> "unresolved ${resolution.reason.value}"

            is Resolution.NotAnalysed -> "not-analysed ${resolution.reason.value}"
        }
        symbolOf(binding.from)?.name.orEmpty() to outcome
    }

    @Test
    fun `external functions and native methods are bound to their c functions`() {
        KrosScope.open(sample.root).use { service ->
            val scan = service.scan()
            assertEquals(0, scan.diagnostics.errors, "${scan.diagnostics.entries}")
            assertEquals(0, scan.diagnostics.warnings, "${scan.diagnostics.entries}")
            assertEquals(
                mapOf(
                    "Java_sample_jni_bridge_Checksum_crc32" to "definition EXACT",
                    "Java_sample_jni_bridge_Checksum_missing" to "unresolved jni.definition-not-found",
                    "Java_sample_jni_bridge_Checksum_nativeVersion" to "definition EXACT",
                    "Java_sample_jni_bridge_JavaNative_add" to "definition EXACT",
                    "Java_sample_jni_bridge_NativeOpsKt_mix" to "declaration PROBABLE",
                ),
                service.graph().outcomes(),
            )
        }
    }

    @Test
    fun `both kinds of native declaration are flagged external by the analyzer`() {
        KrosScope.open(sample.root).use { service ->
            service.scan()
            val external = service.graph().symbols(SymbolQuery(flag = SymbolFlag.EXTERNAL, limit = Int.MAX_VALUE))
            assertEquals(
                listOf("java.method" to "add", "kotlin.function" to "crc32", "kotlin.function" to "missing") +
                    listOf("kotlin.function" to "mix", "kotlin.function" to "nativeVersion"),
                external.map { it.kind.id to it.name }.sortedBy { it.second },
            )
        }
    }

    @Test
    fun `a contract is generated by its declaration and binds with convention evidence`() {
        KrosScope.open(sample.root).use { service ->
            service.scan()
            val graph = service.graph()
            val crc32 = graph.symbols(SymbolQuery(name = "crc32")).single { it.kind.id == "kotlin.function" }
            val generates = graph.outgoing(NodeRef.OfSymbol(crc32.id), setOf(RelationKind.GENERATES)).single()
            assertEquals(EvidenceClass.CONVENTION, generates.evidenceClass)
            val contract = checkNotNull(graph.symbolOf((generates.resolution as Resolution.Resolved).target))
            assertEquals("jni.function", contract.kind.id)
            assertEquals("Java_sample_jni_bridge_Checksum_crc32___3B", contract.attributes["jni.long-name"])
            assertEquals(SymbolOrigin.Generated("jni", NodeRef.OfSymbol(crc32.id)), contract.origin)
            val binding = graph.bindings().first { it.from == NodeRef.OfSymbol(contract.id) }
            assertEquals(EvidenceClass.CONVENTION, binding.evidenceClass)
            assertEquals(crc32.nameLocation, binding.site)
            assertEquals(Certainty.EXACT, (binding.resolution as Resolution.Resolved).certainty)
            val target = graph.symbolOf((binding.resolution as Resolution.Resolved).target)
            assertEquals("bridge/src/main/cpp/checksum.c", target?.declaration?.artifact?.path?.value)
        }
    }

    @Test
    fun `native sources without a function of the name leave every binding unresolved`() {
        nativeFiles.forEach { Files.delete(sample.root.resolve(it)) }
        sample.write("bridge/src/main/cpp/other.c", "void Java_other_Thing_run(void) {}\n")
        KrosScope.open(sample.root).use { service ->
            service.scan()
            assertEquals(
                setOf("unresolved jni.definition-not-found"),
                service.graph().outcomes().values.toSet(),
            )
        }
    }

    @Test
    fun `a workspace without native sources says the native side was not analysed`() {
        nativeFiles.forEach { Files.delete(sample.root.resolve(it)) }
        KrosScope.open(sample.root).use { service ->
            service.scan()
            val graph = service.graph()
            assertEquals(5, graph.outcomes().size)
            assertEquals(setOf("not-analysed jni.native-side-not-analysed"), graph.outcomes().values.toSet())
        }
    }

    @Test
    fun `every resolved target in the workspace names a symbol and an incremental scan agrees`() {
        KrosScope.open(sample.root).use { service ->
            service.scan()
            val definition = "jlong Java_sample_jni_bridge_Checksum_missing(JNIEnv *env, jobject self) { return 0; }\n"
            sample.write("bridge/src/main/cpp/other.c", definition)
            val rescan = service.scan(verify = true)
            val verification = checkNotNull(rescan.verification)
            assertTrue(verification.matches, "${verification.differences}")
            val graph = service.graph()
            assertEquals("definition EXACT", graph.outcomes()["Java_sample_jni_bridge_Checksum_missing"])
            val targets = graph.relationships(RelationshipQuery(limit = Int.MAX_VALUE))
                .mapNotNull { (it.resolution as? Resolution.Resolved)?.target }
                .filterIsInstance<NodeRef.OfSymbol>().map { it.id }
                .filter { (it.identity() as? ParsedSymbolId.Valid)?.identity?.ecosystem == SymbolEcosystem.GRADLE }
            assertEquals(emptyList(), targets.filter { graph.symbol(it) == null }.map { it.value })
        }
    }
}
