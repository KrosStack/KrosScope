/**
 * Scans a Kotlin Multiplatform module with Compose Multiplatform resources, a JVM application that reads them through
 * the public resource class, and a module whose resource class has the package that the plugin derives. The resource
 * class exists only as a signature stub that the synthesizer makes.
 */
class ComposeResourcesIntegrationTest {
    private val sample = SampleWorkspace("cmp")
    private val uiKotlin = "ui/src/commonMain/kotlin/sample/cmp/ui/Greeting.kt"
    private val appKotlin = "app/src/main/kotlin/sample/cmp/app/Main.kt"
    private val extrasKotlin = "extras/src/commonMain/kotlin/sample/cmp/extras/Extras.kt"
    private val strings = "ui/src/commonMain/composeResources/values/strings.xml"

    @AfterTest
    fun cleanUp() {
        sample.close()
    }

    private fun GraphReader.allRelationships(): List<Relationship> =
        relationships(RelationshipQuery(limit = Int.MAX_VALUE))

    private fun GraphReader.symbolOf(relationship: Relationship): Symbol? =
        ((relationship.resolution as? Resolution.Resolved)?.target as? NodeRef.OfSymbol)?.let { symbol(it.id) }

    private fun GraphReader.edgesInto(file: String, qualifiedName: String): List<Relationship> =
        allRelationships().filter { it.site?.artifact?.path?.value == file }
            .filter { symbolOf(it)?.qualifiedName == qualifiedName }

    private fun GraphReader.accessor(qualifiedName: String): Symbol =
        symbols(SymbolQuery(qualifiedName = qualifiedName)).single { it.origin is SymbolOrigin.Generated }

    private fun assertCompilerExact(edges: List<Relationship>, what: String) {
        assertTrue(edges.isNotEmpty(), "No edge to $what")
        edges.forEach {
            assertEquals(EvidenceClass.COMPILER, it.evidenceClass, what)
            assertEquals(Certainty.EXACT, (it.resolution as Resolution.Resolved).certainty, what)
        }
    }

    @Test
    fun `consumers of the resource class bind to the generated accessors with compiler evidence`() {
        KrosScope.open(sample.root).use { service ->
            val scan = service.scan()
            assertEquals(0, scan.diagnostics.errors, "${scan.diagnostics.entries}")
            assertEquals(0, scan.diagnostics.warnings, "${scan.diagnostics.entries}")
            val graph = service.graph()
            assertCompilerExact(graph.edgesInto(uiKotlin, "sample.cmp.resources.greeting"), "greeting")
            assertCompilerExact(graph.edgesInto(uiKotlin, "sample.cmp.resources.ic_flag"), "ic_flag")
            assertCompilerExact(graph.edgesInto(uiKotlin, "sample.cmp.resources.levels"), "levels")
            assertCompilerExact(graph.edgesInto(uiKotlin, "sample.cmp.resources.tasks"), "tasks")
            assertCompilerExact(graph.edgesInto(uiKotlin, "sample.cmp.resources.Res"), "Res")
            assertCompilerExact(graph.edgesInto(appKotlin, "sample.cmp.resources.farewell"), "farewell in the app")
            assertCompilerExact(graph.edgesInto(appKotlin, "sample.cmp.resources.Res.getUri"), "getUri")
        }
    }

    @Test
    fun `an accessor is generated by its resource with convention evidence`() {
        KrosScope.open(sample.root).use { service ->
            service.scan()
            val graph = service.graph()
            val accessor = graph.accessor("sample.cmp.resources.greeting")
            val origin = accessor.origin as SymbolOrigin.Generated
            assertEquals("compose.res", origin.generator)
            assertEquals(Certainty.EXACT, accessor.certainty)
            val generates = graph.incoming(NodeRef.OfSymbol(accessor.id), setOf(RelationKind.GENERATES)).single()
            assertEquals(EvidenceClass.CONVENTION, generates.evidenceClass)
            assertEquals(Certainty.EXACT, (generates.resolution as Resolution.Resolved).certainty)
            val resource = assertNotNull(graph.symbol((generates.from as NodeRef.OfSymbol).id))
            assertEquals("compose.resource.string", resource.kind.id)
            assertEquals(NodeRef.OfSymbol(resource.id), origin.sourceOfTruth)
            assertEquals(strings, resource.declaration?.artifact?.path?.value)
        }
    }

    @Test
    fun `a resource that another configuration defines is the same symbol with a second definition site`() {
        KrosScope.open(sample.root).use { service ->
            service.scan()
            val graph = service.graph()
            val greeting = graph.symbols(SymbolQuery(kindId = "compose.resource.string", name = "greeting")).single()
            val sites = graph.incoming(NodeRef.OfSymbol(greeting.id), setOf(RelationKind.REFERENCES))
            assertEquals(
                listOf("ui/src/commonMain/composeResources/values-de/strings.xml"),
                sites.filter { it.subKind == "definition" }.map { it.site?.artifact?.path?.value },
            )
        }
    }

    @Test
    fun `a package that the plugin derives gives heuristic symbols that the compiler still binds`() {
        KrosScope.open(sample.root).use { service ->
            service.scan()
            val graph = service.graph()
            val accessor = graph.accessor("cmp.extras.generated.resources.extra_title")
            assertEquals(Certainty.HEURISTIC, accessor.certainty)
            assertCompilerExact(graph.edgesInto(extrasKotlin, "cmp.extras.generated.resources.extra_title"), "extra")
            val generates = graph.incoming(NodeRef.OfSymbol(accessor.id), setOf(RelationKind.GENERATES)).single()
            assertEquals(Certainty.HEURISTIC, (generates.resolution as Resolution.Resolved).certainty)
        }
    }

    @Test
    fun `every resolved target in the workspace names a symbol, the generated ones included`() {
        KrosScope.open(sample.root).use { service ->
            service.scan()
            val graph = service.graph()
            val targets = graph.allRelationships().mapNotNull { (it.resolution as? Resolution.Resolved)?.target }
                .filterIsInstance<NodeRef.OfSymbol>().map { it.id }
                .filter { (it.identity() as? ParsedSymbolId.Valid)?.identity?.ecosystem == SymbolEcosystem.GRADLE }
            assertTrue(targets.size > 10, "Too few targets to say anything: ${targets.size}")
            assertEquals(emptyList(), targets.filter { graph.symbol(it) == null }.map { it.value })
            assertTrue(targets.any { graph.symbol(it)?.origin is SymbolOrigin.Generated })
        }
    }
}
