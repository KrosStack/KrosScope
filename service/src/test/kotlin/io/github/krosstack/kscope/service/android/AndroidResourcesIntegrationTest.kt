/**
 * Scans a small Android application and library with the real analyzer worker. Kotlin and Java files refer to `R`,
 * which exists only as a signature stub that the resource synthesizer makes, and layouts refer to strings of their own
 * module and of the library.
 */
class AndroidResourcesIntegrationTest {
    private val sample = SampleWorkspace("droid")
    private val mainKotlin = "app/src/main/kotlin/sample/droid/app/Main.kt"
    private val legacyJava = "app/src/main/java/sample/droid/app/Legacy.java"
    private val libKotlin = "lib/src/main/kotlin/sample/droid/lib/LibScreen.kt"
    private val layout = "app/src/main/res/layout/activity_main.xml"
    private val libStrings = "lib/src/main/res/values/strings.xml"
    private val twoStrings = "<resources>\n" +
        "    <string name=\"lib_title\">Changed</string>\n" +
        "    <string name=\"lib_extra\">x</string>\n" +
        "</resources>\n"

    @AfterTest
    fun cleanUp() {
        sample.close()
    }

    private fun GraphReader.allRelationships(): List<Relationship> =
        relationships(RelationshipQuery(limit = Int.MAX_VALUE))

    private fun GraphReader.generatedField(qualifiedName: String): Symbol =
        symbols(SymbolQuery(qualifiedName = qualifiedName)).single { it.origin is SymbolOrigin.Generated }

    private fun GraphReader.symbolOf(relationship: Relationship): Symbol? =
        ((relationship.resolution as? Resolution.Resolved)?.target as? NodeRef.OfSymbol)?.let { symbol(it.id) }

    private fun GraphReader.edgesInto(file: String, qualifiedName: String): List<Relationship> {
        val inFile = allRelationships().filter { it.site?.artifact?.path?.value == file }
        return inFile.filter { symbolOf(it)?.qualifiedName == qualifiedName }
    }

    private fun assertCompilerExact(edges: List<Relationship>, what: String) {
        assertTrue(edges.isNotEmpty(), "No edge to $what")
        edges.forEach {
            assertEquals(EvidenceClass.COMPILER, it.evidenceClass, what)
            assertEquals(Certainty.EXACT, (it.resolution as Resolution.Resolved).certainty, what)
        }
    }

    @Test
    fun `kotlin and java consumers of R resolve to the generated fields with compiler evidence`() {
        KrosScope.open(sample.root).use { service ->
            val scan = service.scan()
            assertEquals(0, scan.diagnostics.errors, "${scan.diagnostics.entries}")
            assertEquals(0, scan.diagnostics.warnings, "${scan.diagnostics.entries}")
            val graph = service.graph()
            assertCompilerExact(graph.edgesInto(mainKotlin, "sample.droid.app.R.string.app_name"), "app_name")
            assertCompilerExact(graph.edgesInto(mainKotlin, "sample.droid.app.R.layout.activity_main"), "layout")
            assertCompilerExact(graph.edgesInto(mainKotlin, "sample.droid.app.R.id.title"), "id")
            assertCompilerExact(graph.edgesInto(legacyJava, "sample.droid.app.R.string.greeting"), "greeting")
            assertCompilerExact(graph.edgesInto(libKotlin, "sample.droid.lib.R.string.lib_title"), "lib_title")
        }
    }

    @Test
    fun `a generated field is generated by its resource with convention evidence`() {
        KrosScope.open(sample.root).use { service ->
            service.scan()
            val graph = service.graph()
            val field = graph.generatedField("sample.droid.app.R.string.app_name")
            val origin = field.origin as SymbolOrigin.Generated
            assertEquals("android.r", origin.generator)
            val generates = graph.incoming(NodeRef.OfSymbol(field.id), setOf(RelationKind.GENERATES)).single()
            assertEquals(EvidenceClass.CONVENTION, generates.evidenceClass)
            assertEquals(Certainty.EXACT, (generates.resolution as Resolution.Resolved).certainty)
            val resource = assertNotNull(graph.symbol((generates.from as NodeRef.OfSymbol).id))
            assertEquals("android.resource.string", resource.kind.id)
            assertEquals(NodeRef.OfSymbol(resource.id), origin.sourceOfTruth)
            assertEquals(resource.declaration?.artifact?.path?.value, "app/src/main/res/values/strings.xml")
        }
    }

    @Test
    fun `references between resource files resolve in the module and in the library`() {
        KrosScope.open(sample.root).use { service ->
            service.scan()
            val graph = service.graph()
            val fromLayout = graph.allRelationships().filter { it.site?.artifact?.path?.value == layout }
                .filter { it.kind == RelationKind.REFERENCES && it.subKind != "definition" }
            val byTarget = fromLayout.associateBy { graph.symbolOf(it)?.qualifiedName }
            val own = byTarget.getValue("sample.droid.app.R.string.app_name")
            val library = byTarget.getValue("sample.droid.lib.R.string.lib_title")
            listOf(own, library).forEach {
                assertEquals(EvidenceClass.TEXTUAL, it.evidenceClass)
                assertEquals(Certainty.EXACT, (it.resolution as Resolution.Resolved).certainty)
            }
            assertEquals(2, fromLayout.size)
        }
    }

    @Test
    fun `every resolved target in the workspace names a symbol, the generated ones included`() {
        KrosScope.open(sample.root).use { service ->
            service.scan()
            val graph = service.graph()
            val targets = graph.allRelationships().mapNotNull { (it.resolution as? Resolution.Resolved)?.target }
                .filterIsInstance<NodeRef.OfSymbol>().map { it.id }
                .filter { (it.identity() as? ParsedSymbolId.Valid)?.identity?.ecosystem == SymbolEcosystem.GRADLE }
            assertTrue(targets.size > 10, "Too few targets to say anything: ${targets.size}")
            assertEquals(emptyList(), targets.filter { graph.symbol(it) == null }.map { it.value })
            assertTrue(targets.any { graph.symbol(it)?.origin is SymbolOrigin.Generated })
        }
    }

    @Test
    fun `changing the text of a string produces little and a new string produces the dependents too`() {
        KrosScope.open(sample.root).use { service ->
            val first = service.scan()
            assertEquals(
                19 + HISTORY_UNIT + linkerCount,
                first.unitsProduced,
                "Discovery, build model, 3 resource files, 2 manifests, 5 synthesizer units (R, view binding, the " +
                    "build config of 2 modules and the generator inputs), the copy sources of the workspace, 2 " +
                    "source sets, the load calls and the Ktor routes of each of the 2 source sets, the history, the " +
                    "linkers",
            )

            sample.write(libStrings, "<resources>\n    <string name=\"lib_title\">Changed</string>\n</resources>\n")
            val text = service.scan()
            assertEquals(3 + linkerCount, text.unitsProduced, "Discovery, the file, the R synthesizer and the linkers")

            sample.write(libStrings, twoStrings)
            val name = service.scan(verify = true)
            assertTrue(
                name.unitsProduced > text.unitsProduced,
                "The stub changed, so its source sets are analysed again",
            )
            val verification = assertNotNull(name.verification)
            assertTrue(verification.matches, "${verification.differences}")
            assertNotNull(service.graph().generatedField("sample.droid.lib.R.string.lib_extra"))
        }
    }
}
