/**
 * Scans the `viewdroid` sample with the real analyzer worker. Kotlin and Java files use the binding class of a layout
 * and `BuildConfig`, which exist only as signature stubs that the synthesizers make.
 */
internal class AndroidSurfacesIntegrationTest : SurfacesWorkspace() {

    @Test
    fun `kotlin and java consumers of a binding class and of BuildConfig resolve to the generated symbols`() {
        KrosScope.open(sample.root).use { service ->
            val scan = service.scan()
            assertEquals(0, scan.diagnostics.errors, "${scan.diagnostics.entries}")
            assertEquals(0, scan.diagnostics.warnings, "${scan.diagnostics.entries}")
            val graph = service.graph()
            val binding = "$app.databinding.ActivityMainBinding"
            assertCompilerExact(graph.edgesInto(mainKotlin, binding), "the binding class in Kotlin")
            assertCompilerExact(graph.edgesInto(mainKotlin, "$binding.bind"), "bind")
            assertCompilerExact(graph.edgesInto(mainKotlin, "$binding.title"), "the title field in Kotlin")
            assertCompilerExact(graph.edgesInto(legacyJava, binding), "the binding class in Java")
            assertCompilerExact(graph.edgesInto(legacyJava, "$binding.title"), "the title field in Java")
            assertCompilerExact(graph.edgesInto(mainKotlin, "$app.BuildConfig.ENDPOINT"), "ENDPOINT")
            assertCompilerExact(graph.edgesInto(legacyJava, "$app.BuildConfig.VERBOSE"), "VERBOSE")
            assertCompilerExact(graph.edgesInto(legacyJava, "$app.BuildConfig.DEBUG"), "DEBUG")
            val library = "sample.viewdroid.lib.BuildConfig.LIBRARY_PACKAGE_NAME"
            assertCompilerExact(graph.edgesInto(libKotlin, library), "LIBRARY_PACKAGE_NAME")
        }
    }

    @Test
    fun `a binding class is generated by its layout and a field by its id, BuildConfig by the build script`() {
        KrosScope.open(sample.root).use { service ->
            service.scan()
            val graph = service.graph()
            val binding = graph.generated("$app.databinding.ActivityMainBinding")
            val byLayout = graph.incoming(NodeRef.OfSymbol(binding.id), setOf(RelationKind.GENERATES)).single()
            assertEquals(EvidenceClass.CONVENTION, byLayout.evidenceClass)
            val layoutSymbol = assertNotNull(graph.symbol((byLayout.from as NodeRef.OfSymbol).id))
            assertEquals("android.resource.layout", layoutSymbol.kind.id)
            assertEquals(layout, layoutSymbol.declaration?.artifact?.path?.value)
            val title = graph.generated("$app.databinding.ActivityMainBinding.title")
            val byId = graph.incoming(NodeRef.OfSymbol(title.id), setOf(RelationKind.GENERATES)).single()
            assertEquals("android.resource.id", graph.symbol((byId.from as NodeRef.OfSymbol).id)?.kind?.id)
            val endpoint = graph.generated("$app.BuildConfig.ENDPOINT")
            val byScript = graph.incoming(NodeRef.OfSymbol(endpoint.id), setOf(RelationKind.GENERATES)).single()
            assertEquals(EvidenceClass.CONVENTION, byScript.evidenceClass)
            assertEquals("app/build.gradle.kts", (byScript.from as NodeRef.OfArtifact).ref.path.value)
        }
    }

    @Test
    fun `every resolved target in the workspace names a symbol, the generated ones included`() {
        KrosScope.open(sample.root).use { service ->
            service.scan()
            val graph = service.graph()
            val targets = graph.allRelationships().mapNotNull { (it.resolution as? Resolution.Resolved)?.target }
                .filterIsInstance<NodeRef.OfSymbol>().map { it.id }
                .filter { (it.identity() as? ParsedSymbolId.Valid)?.identity?.ecosystem == SymbolEcosystem.GRADLE }
            assertTrue(targets.size > 30, "Too few targets to say anything: ${targets.size}")
            assertEquals(emptyList(), targets.filter { graph.symbol(it) == null }.map { it.value })
        }
    }

    @Test
    fun `a new id in a layout adds a field to the binding class and the scan agrees with a rebuild`() {
        KrosScope.open(sample.root).use { service ->
            service.scan()
            val extra = "$app.databinding.ActivityMainBinding.extra"
            assertTrue(service.graph().symbols(SymbolQuery(qualifiedName = extra)).isEmpty())
            val withExtra = "<Button android:id=\"@+id/extra\" />\n</LinearLayout>"
            sample.write(layout, sample.root.resolve(layout).toFile().readText().replace("</LinearLayout>", withExtra))
            val changed = service.scan(verify = true)
            val verification = assertNotNull(changed.verification)
            assertTrue(verification.matches, "${verification.differences}")
            assertNotNull(service.graph().generated(extra))
        }
    }
}
